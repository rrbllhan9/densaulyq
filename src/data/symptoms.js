export function findSymptom(text) {
  const lower = text.toLowerCase()
  let bestMatch = null
  let bestScore = 0

  for (const symptom of symptomsDB) {
    let score = 0
    for (const kw of symptom.keywords) {
      if (lower.includes(kw)) score++
    }
    if (score > bestScore) {
      bestScore = score
      bestMatch = symptom
    }
  }

  return bestScore > 0 ? bestMatch : null
}
