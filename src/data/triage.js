// Умный браузерный триаж — без бэкенда и без API.
// 1) Сначала ищем «красные флаги» (признаки неотложного состояния).
// 2) Иначе сопоставляем жалобу с базой симптомов по ключевым словам.
// 3) Добавляем тёплое сообщение-поддержку под уровень срочности.
import { symptomsDB } from './symptoms'

// Признаки, при которых нужно сразу звонить 103 — они важнее любого совпадения.
const RED_FLAGS = [
  'не могу дышать', 'тяжело дышать', 'задыха', 'нечем дышать', 'одышка в покое',
  'боль в груди', 'давит груд', 'жжёт в груди', 'жжет в груди',
  'теря сознан', 'потеря сознан', 'обморок', 'упал в обморок',
  'судорог', 'припадок',
  'не могу говорить', 'перекосило', 'онемела рука', 'онемело лицо', 'паралич',
  'сильное кровотеч', 'рвота кровью', 'кровь изо рта',
  'не реагирует', 'без сознания',
]

const EMERGENCY = {
  id: 'emergency',
  emoji: '🚨',
  title: 'Похоже на неотложное состояние',
  severity: 'high',
  firstAid: [
    'Позвоните на бесплатный номер 103 прямо сейчас',
    'Не оставайтесь в одиночестве — попросите кого-то быть рядом',
    'Сядьте или лягте в удобное положение, расстегните тесную одежду',
    'Постарайтесь дышать медленно и ровно, пока едет помощь',
  ],
  specialist: {
    name: 'Скорая помощь — 103',
    reason: 'Такие признаки требуют срочного осмотра. Лучше перестраховаться и вызвать помощь.',
  },
  medications: [],
  warning: 'Не ждите, что «само пройдёт». Если есть боль в груди, трудно дышать или спутанность — звоните 103.',
}

const REASSURANCE = {
  emergency:
    'Я рядом. Сейчас главное — не паниковать и быстро вызвать помощь. Сделаем это вместе, по шагам.',
  high: 'Спасибо, что описали. Это лучше не откладывать — давайте я подскажу, что сделать сейчас 🤍',
  medium:
    'Понимаю, это может тревожить. Давайте спокойно разберёмся, что можно сделать прямо сейчас 🌿',
  low: 'Скорее всего, ничего страшного — с этим вполне можно справиться дома. Давайте посмотрим 🌿',
}

// Приводим текст к единому виду: нижний регистр, ё→е, без лишних знаков.
function normalize(text) {
  return text.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9\s]/gi, ' ')
}

export function triage(rawText) {
  const text = normalize(rawText)

  // Шаг 1 — красные флаги.
  if (RED_FLAGS.some(flag => text.includes(normalize(flag)))) {
    return { symptom: EMERGENCY, reassurance: REASSURANCE.emergency }
  }

  // Шаг 2 — лучшее совпадение по ключевым словам базы.
  let best = null
  let bestScore = 0
  for (const symptom of symptomsDB) {
    let score = 0
    for (const kw of symptom.keywords) {
      if (text.includes(normalize(kw))) score++
    }
    if (score > bestScore) {
      bestScore = score
      best = symptom
    }
  }

  if (!best) return null

  // Шаг 3 — тёплое сообщение под уровень срочности.
  return { symptom: best, reassurance: REASSURANCE[best.severity] || REASSURANCE.medium }
}
